/**
 * ЕДИНСТВЕННОЕ место с адресом backend'а. Меняешь адрес — меняешь только
 * значение SERVER_BASE_URL ниже, пересобираешь клиент — готово. Раньше
 * "http://localhost:8000" был захардкожен прямо внутри js/api.js — здесь
 * его специально вынесли отдельно, чтобы под прод/стейджинг/другой порт
 * не нужно было искать нужную строчку по всему файлу с запросами.
 *
 * Так же переносится на любой другой адрес — свой сервер, VPS, домен с https:
 *   export const SERVER_BASE_URL = "https://api.roadwits.example.com";
 *
 * ВАЖНО про CORS: backend (roadwits-server/app/main.py) разрешает CORS
 * через переменную CORS_ORIGINS в roadwits-server/.env. По умолчанию там "*"
 * (разрешено всё, см. .env) — это ок для разработки, но если сузишь
 * CORS_ORIGINS до конкретных origin на проде, схема запроса (http/https)
 * и хост в SERVER_BASE_URL ниже должны быть именно тем адресом, с которого
 * реально идут запросы этого клиента.
 */
export const SERVER_BASE_URL = "http://localhost:8000";

/** Таймаут одного запроса к серверу, мс. Если сервер не отвечает дольше —
 * запрос обрывается и клиент показывает ошибку, вместо того чтобы виснуть
 * бесконечно (например, если сервер поднят, но недоступен по сети). */
export const REQUEST_TIMEOUT_MS = 15000;

